// Правило-бот: отвечает на типовые вопросы по личному кабинету.
// Возвращает { text, actionLabel, actionHref }. text — обычный текст с \n.

export function botReply(text, firstName) {
  const t = (text || '').toLowerCase();

  if (t.includes('справк')) {
    return {
      text:
        'Это можно сделать в разделе «Документы»:\n1. Откройте «Заказать документы».\n2. Выберите «Справка об обучении» и проверьте имя и группу.\n3. Укажите формат: электронный PDF или печатный документ.\n4. Для печатного выберите место получения и нажмите «Заказать документ».',
      actionLabel: 'Открыть заказ документов ↗',
      actionHref: '/documents',
    };
  }
  if (t.includes('дедлайн')) {
    return {
      text:
        'Ближайшие дедлайны:\n• Эссе по истории — сегодня до 23:59\n• Практическая работа № 3 — пн, 23 ноя до 18:00\n• Доклад по менеджменту — ср, 25 ноя до 12:00',
      actionLabel: 'Открыть календарь ↗',
      actionHref: '/calendar',
    };
  }
  if (t.includes('курсов')) {
    return {
      text:
        'Курсовую отправляют в «Документы» → «Загрузка документов» → «Курсовая работа»:\n1. Проверьте дисциплину и тему.\n2. Прикрепите файл DOCX или PDF.\n3. Нажмите «Отправить на проверку».',
      actionLabel: 'Открыть загрузку ↗',
      actionHref: '/documents',
    };
  }
  if (t.includes('балл') || t.includes('оценк') || t.includes('успеваемост')) {
    return {
      text: 'Баллы и посещаемость — в разделе «Успеваемость». Там можно выбрать семестр и период дат.',
      actionLabel: 'Открыть успеваемость ↗',
      actionHref: '/grades',
    };
  }
  if (t.includes('расписан')) {
    return {
      text: 'Расписание на сегодня и на неделю — в разделе «Календарь». Недели можно листать стрелками.',
      actionLabel: 'Открыть календарь ↗',
      actionHref: '/calendar',
    };
  }
  if (t.includes('зачёт') || t.includes('зачет')) {
    return {
      text: 'Итоги аттестации по семестрам — в разделе «Зачётная книжка». Там есть все прошлые семестры.',
      actionLabel: 'Открыть зачётную книжку ↗',
      actionHref: '/gradebook',
    };
  }
  if (t.includes('уведомлен') || t.includes('колокольчик')) {
    return {
      text: 'Все уведомления собраны в разделе «Уведомления» — откройте его через колокольчик вверху справа.',
      actionLabel: 'Открыть уведомления ↗',
      actionHref: '/notifications',
    };
  }
  if (t.includes('достижен') || t.includes('наград')) {
    return {
      text: 'Награды и прогресс — в разделе «Достижения». Там же можно фильтровать по статусам.',
      actionLabel: 'Открыть достижения ↗',
      actionHref: '/achievements',
    };
  }
  return {
    text:
      'Я пока учусь отвечать на такие вопросы, ' +
      firstName +
      '. Могу помочь с расписанием, баллами, документами, дедлайнами и уведомлениями — спроси об этом!',
  };
}
