async function img(file, width = 600) {
  const meta = await sharp(file).metadata();
  const height = Math.round((width * meta.height) / meta.width);
  return new Paragraph({
    alignment: AlignmentType.CENTER,
    spacing: { before: 100, after: 60 },
    children: [
      new ImageRun({ type: 'png', data: fs.readFileSync(file), transformation: { width, height } }),
    ],
  });
}

function caption(t) {
  return new Paragraph({
    alignment: AlignmentType.CENTER,
    spacing: { after: 200 },
    children: [new TextRun({ text: t, italics: true, size: 18, color: MUTED })],
  });
}

function placeholder(text) {
  return new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    rows: [
      new TableRow({
        children: [
          new TableCell({
            shading: { type: ShadingType.CLEAR, fill: 'f5f8f5' },
            margins: { top: 420, bottom: 420 },
            borders: {
              top: { style: BorderStyle.DASHED, size: 6, color: 'cfe0d5' },
              bottom: { style: BorderStyle.DASHED, size: 6, color: 'cfe0d5' },
              left: { style: BorderStyle.DASHED, size: 6, color: 'cfe0d5' },
              right: { style: BorderStyle.DASHED, size: 6, color: 'cfe0d5' },
            },
            children: [
              new Paragraph({
                alignment: AlignmentType.CENTER,
                children: [new TextRun({ text, italics: true, size: 19, color: MUTED })],
              }),
            ],
          }),
        ],
      }),
    ],
  });
}

function table(headers, rows, widths) {
  const headerRow = new TableRow({
    tableHeader: true,
    children: headers.map(
      (h, i) =>
        new TableCell({
          shading: { type: ShadingType.CLEAR, fill: GREEN },
          width: widths ? { size: widths[i], type: WidthType.PERCENTAGE } : undefined,
          margins: { top: 90, bottom: 90, left: 100, right: 100 },
          children: [new Paragraph({ children: [new TextRun({ text: h, bold: true, color: 'ffffff', size: 20 })] })],
        })
    ),
  });
  const bodyRows = rows.map(
    (r) =>
      new TableRow({
        children: r.map(
          (cell, i) =>
            new TableCell({
              width: widths ? { size: widths[i], type: WidthType.PERCENTAGE } : undefined,
              margins: { top: 80, bottom: 80, left: 100, right: 100 },
              children: [new Paragraph({ children: [new TextRun({ text: cell, size: 20, color: DARK })] })],
            })
        ),
      })
  );
  return new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    rows: [headerRow, ...bodyRows],
  });
}

